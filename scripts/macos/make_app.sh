#!/usr/bin/env bash
# Builds Bloodborne.app in the repository folder: double-click (or keep in the Dock) to play
# without a Terminal window. The app is a small launcher for this checkout: it uses the same
# launch.conf as Bloodborne.command, runs run.sh in the background and writes the game's log to
# ~/Library/Logs/Bloodborne/game.log (the previous session's in game.previous.log). If the game
# stops with an error, a dialog offers the log.
#
# The game window runs from inside the bundle (a link to out/bbgpu-host), so the Dock shows
# "Bloodborne". The icon is made from your game's sce_sys/icon0.png, so the app is built
# locally and never committed (Bloodborne.app is in .gitignore).
#
# usage: bash scripts/macos/make_app.sh     (again after moving the repository)
set -euo pipefail
cd -- "$(dirname -- "$0")/../.."
repo=$PWD
app=$repo/Bloodborne.app
rm -rf "$app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"

cat > "$app/Contents/Info.plist" <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>Bloodborne</string>
    <key>CFBundleDisplayName</key><string>Bloodborne</string>
    <key>CFBundleIdentifier</key><string>io.github.wooloomooloo2.bloodborne-mac-port</string>
    <key>CFBundleExecutable</key><string>Bloodborne</string>
    <key>CFBundleIconFile</key><string>Bloodborne</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>0.3</string>
    <key>LSMinimumSystemVersion</key><string>15.0</string>
    <key>LSApplicationCategoryType</key><string>public.app-category.role-playing-games</string>
    <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
EOF

# The launcher. The repository path is fixed at build time.
{
    printf '#!/bin/bash\n'
    printf '# Bloodborne.app launcher, generated by scripts/macos/make_app.sh.\n'
    printf 'repo=%q\n' "$repo"
    cat <<'EOF'
app=$(cd "$(dirname "$0")/../.." && pwd)
logs=$HOME/Library/Logs/Bloodborne
mkdir -p "$logs"
alert() { # title, message
    osascript - "$1" "$2" >/dev/null 2>&1 <<'OSA'
on run argv
    display alert (item 1 of argv) message (item 2 of argv) as critical
end run
OSA
}
if ! cd "$repo" 2>/dev/null; then
    alert "Bloodborne" "The repository folder $repo is gone. Run scripts/macos/make_app.sh again from its new place."
    exit 1
fi
if pgrep -qx bbgpu-host || pgrep -qx bb-probe; then
    alert "Bloodborne is already running" "Only one copy of the game can run at a time."
    exit 0
fi
source scripts/macos/launch_common.sh
if ! bb_prepare_launch > "$logs/launch.txt" 2>&1; then
    alert "Bloodborne cannot start" "$(cat "$logs/launch.txt")"
    exit 1
fi
[[ -f $logs/game.log ]] && mv -f "$logs/game.log" "$logs/game.previous.log"
# The game window process runs from the bundle: the Dock shows this app's name and icon.
export BB_GPU_HOST=$app/Contents/MacOS/bbgpu-host
(
    status=0
    bash run.sh > "$logs/game.log" 2>&1 || status=$?
    if (( status != 0 )); then
        answer=$(osascript - "$status" "$logs/game.log" 2>/dev/null <<'OSA'
on run argv
    set r to display alert "Bloodborne stopped" message ("The game exited with status " & (item 1 of argv) & ". The log is " & (item 2 of argv) & ".") as critical buttons {"Show Log", "OK"} default button "OK"
    return button returned of r
end run
OSA
)
        [[ $answer == "Show Log" ]] && open -a Console "$logs/game.log"
    fi
) < /dev/null > /dev/null 2>&1 &
disown
exit 0
EOF
} > "$app/Contents/MacOS/Bloodborne"
chmod +x "$app/Contents/MacOS/Bloodborne"
ln -s "$repo/out/bbgpu-host" "$app/Contents/MacOS/bbgpu-host"

# Icon from the game's own artwork, when the game folder is known.
game=
if [[ -f launch.conf ]]; then game=$(set -a; source ./launch.conf; printf '%s' "${BB_GAME_DIR:-}"); fi
[[ -z $game && -f ../CUSA03173/eboot.bin ]] && game=$(cd ../CUSA03173 && pwd)
if [[ -n $game && -f $game/sce_sys/icon0.png ]]; then
    set_dir=$(mktemp -d)/Bloodborne.iconset
    mkdir -p "$set_dir"
    for size in 16 32 128 256 512; do
        sips -z $size $size "$game/sce_sys/icon0.png" --out "$set_dir/icon_${size}x${size}.png" >/dev/null
        double=$((size * 2))
        sips -z $double $double "$game/sce_sys/icon0.png" --out "$set_dir/icon_${size}x${size}@2x.png" >/dev/null
    done
    iconutil -c icns "$set_dir" -o "$app/Contents/Resources/Bloodborne.icns"
    rm -rf "$(dirname "$set_dir")"
else
    echo "No game folder known yet (launch.conf): the app has no icon. Run this again after the first launch."
fi
touch "$app"
echo "Built $app"
